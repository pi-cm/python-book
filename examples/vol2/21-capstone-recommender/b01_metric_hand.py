from 순위지표 import ndcg_at_k, recall_at_k

이름 = {41: "성수 고기", 17: "종로 분식", 102: "강남 카페", 233: "홍대 일식", 5: "잠실 한식"}
정답 = {41, 17}                       # 이 사용자가 다음 달에 처음 가서 좋았던 두 곳

목록들 = {
    "가": [41, 102, 17, 233, 5],       # 정답이 1등, 3등
    "나": [102, 233, 5, 17, 41],       # 같은 다섯 곳, 정답이 4등, 5등
    "다": [17, 41, 102, 233, 5],       # 정답이 1등, 2등
}
for 이름표, 목록 in 목록들.items():
    print(f"목록 {이름표}: {[이름[i] for i in 목록[:3]]} ...")
    for k in (3, 5):
        print(f"   k={k}: Recall {recall_at_k(목록, 정답, k):.3f}, NDCG {ndcg_at_k(목록, 정답, k):.3f}")
