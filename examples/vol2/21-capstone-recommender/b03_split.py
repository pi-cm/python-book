# [2권 Chapter 21. 종합 프로젝트: 맛집 추천 AI · 21.3 시간 순서로 나누기 · manuscript-vol2/chapters/21-capstone-recommender.md:326]
import pandas as pd

from 맛집데이터 import 데이터_만들기, 시간으로_나누기
from 순위지표 import 평가셋_만들기

데이터 = 데이터_만들기(씨앗=0)
학습, 검증, 시험 = 시간으로_나누기(데이터.방문)
for 이름, 조각 in [("학습", 학습), ("검증", 검증), ("시험", 시험)]:
    print(f"{이름}: {조각['날짜'].min():3}일 ~ {조각['날짜'].max():3}일, 방문 {len(조각):6,}번")

처음_보는_사용자 = set(시험["사용자"]) - set(학습["사용자"])
처음_보는_식당 = set(시험["식당"]) - set(학습["식당"])
print(f"시험 기간 사용자 중 학습 기록이 없는 사람: {len(처음_보는_사용자)}명")
print(f"시험 기간 식당 중 학습 기록이 없는 곳: {len(처음_보는_식당)}곳")

검증셋 = 평가셋_만들기(학습, 검증, 데이터.식당)
시험셋 = 평가셋_만들기(pd.concat([학습, 검증]), 시험, 데이터.식당)
for 이름, 셋 in [("검증", 검증셋), ("시험", 시험셋)]:
    정답_수 = sum(len(답) for 답 in 셋.정답)
    print(f"{이름} 평가: 사용자 {len(셋.사용자):,}명, 맞힐 식당 평균 {정답_수 / len(셋.사용자):.2f}곳, "
          f"후보에서 빼는 칸 평균 {셋.제외.sum(axis=1).mean():.1f}곳")
