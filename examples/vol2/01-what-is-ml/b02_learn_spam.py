from collections import Counter

# 사람이 스팸/정상 표시를 붙여 둔 메일 제목 (예제용으로 만든 데이터)
학습_메일 = [
    ("경품 당첨 축하 안내", "스팸"),
    ("무료 쿠폰 지금 받기", "스팸"),
    ("무.료 상담 지금 전화", "스팸"),
    ("저금리 대환 대출 한정 안내", "스팸"),
    ("저금리 상품 지금 신청", "스팸"),
    ("한정 특가 무료 배송", "스팸"),
    ("내일 회의 자료 공유", "정상"),
    ("도서관 책 대출 기한 안내", "정상"),
    ("주말 등산 일정 공유", "정상"),
    ("회의 시간 변경 안내", "정상"),
    ("어머니 생신 선물 상의", "정상"),
    ("책 모임 자료 정리", "정상"),
]

# 1) 학습: 단어마다 스팸과 정상에 몇 번 나왔는지 센다
스팸_단어 = Counter()
정상_단어 = Counter()
for 제목, 표시 in 학습_메일:
    if 표시 == "스팸":
        스팸_단어.update(제목.split())
    else:
        정상_단어.update(제목.split())


def 스팸_점수(제목: str) -> int:
    """단어마다 (스팸 등장 수 - 정상 등장 수)를 더한다."""
    return sum(스팸_단어[w] - 정상_단어[w] for w in 제목.split())


# 2) 예측: 처음 보는 메일에 점수를 매긴다
새_메일 = [
    "무.료 체험 지금 신청",
    "저금리 대환 특가 안내",
    "도서관 대출 연장 안내",
    "다음 주 회의 자료",
]
for 제목 in 새_메일:
    점수 = 스팸_점수(제목)
    판정 = "스팸" if 점수 > 0 else "정상"
    print(f"[{판정}] 점수 {점수:+d}  {제목}")
