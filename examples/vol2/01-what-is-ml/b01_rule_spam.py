# [2권 Chapter 1. 머신러닝이란: 규칙을 짜지 않고 데이터로 배우기 · 들어가며: 스팸 메일, if 문으로 거를 수 있을까요? · manuscript-vol2/chapters/01-what-is-ml.md:16]
def 스팸인가(제목: str) -> bool:
    """사람이 정해 둔 규칙(금지어)으로 스팸을 가려낸다."""
    금지어 = ["무료", "당첨", "대출"]
    for 단어 in 금지어:
        if 단어 in 제목:
            return True
    return False


메일들 = [
    "축하합니다 경품 당첨 안내",
    "무료 체험 쿠폰이 도착했어요",
    "내일 회의 자료 공유드립니다",
    "무.료 상담 지금 바로 전화 주세요",
    "저금리 대환 상품 한정 안내",
    "도서관 책 대출 기한이 내일까지예요",
]
for 제목 in 메일들:
    판정 = "스팸" if 스팸인가(제목) else "정상"
    print(f"[{판정}] {제목}")
