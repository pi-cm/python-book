# 어텐션 가중치 표 (배치 1, 헤드 32, T × T)를 bfloat16(2바이트)으로 담으면 몇 바이트일까
헤드_수, 칸_크기 = 32, 2
for T in [128, 1_024, 8_192, 131_072]:
    바이트 = 헤드_수 * T * T * 칸_크기
    print(f"문맥 {T:>7,}글자: 가중치 표 {바이트 / 1024 ** 3:10.3f} GB (층 하나에)")
