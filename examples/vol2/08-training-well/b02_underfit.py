# [2권 Chapter 8. 학습 잘 시키기 · 8.1 과적합과 과소적합 진단하기 · manuscript-vol2/chapters/08-training-well.md:208]
import torch

from 학습도구 import 데이터_준비, 로더_만들기, 모델_만들기, 평가, 한_에폭_학습

(X_학습, y_학습), (X_검증, y_검증), _ = 데이터_준비()
실험들 = {
    "은닉 2칸짜리 작은 모델": dict(은닉=2, lr=1e-3),
    "학습률 1e-5 (너무 작음)": dict(은닉=256, lr=1e-5),
    "은닉 256칸, 학습률 1e-3": dict(은닉=256, lr=1e-3),
}
for 이름, 설정 in 실험들.items():
    torch.manual_seed(0)
    로더 = 로더_만들기(X_학습, y_학습)
    모델 = 모델_만들기(은닉=설정["은닉"])
    옵티마이저 = torch.optim.Adam(모델.parameters(), lr=설정["lr"])
    for 에폭 in range(150):
        한_에폭_학습(모델, 로더, 옵티마이저)
    학습_손실, 학습_정확도 = 평가(모델, X_학습, y_학습)
    검증_손실, 검증_정확도 = 평가(모델, X_검증, y_검증)
    print(f"학습 {학습_손실:.3f} ({학습_정확도:6.1%})  "
          f"검증 {검증_손실:.3f} ({검증_정확도:5.1%})  <- {이름}")
