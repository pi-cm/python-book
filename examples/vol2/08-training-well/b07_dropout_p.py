import torch

from 학습도구 import 데이터_준비, 로더_만들기, 모델_만들기, 평가, 한_에폭_학습

(X_학습, y_학습), (X_검증, y_검증), _ = 데이터_준비()

print("드롭아웃  학습손실  학습정확도  검증손실  검증정확도")
for p in [0.0, 0.2, 0.5, 0.7]:
    torch.manual_seed(0)
    로더 = 로더_만들기(X_학습, y_학습)
    모델 = 모델_만들기(드롭아웃=p)
    옵티마이저 = torch.optim.Adam(모델.parameters(), lr=1e-3)
    for 에폭 in range(150):
        한_에폭_학습(모델, 로더, 옵티마이저)
    학습_손실, 학습_정확도 = 평가(모델, X_학습, y_학습)
    검증_손실, 검증_정확도 = 평가(모델, X_검증, y_검증)
    print(f"{p:8}  {학습_손실:8.3f}  {학습_정확도:9.1%}  {검증_손실:8.3f}  {검증_정확도:9.1%}")
