import torch

기온 = torch.tensor([[ 2.0, 13.5, 25.7, 15.0],
                     [ 4.5, 15.0, 25.0, 17.5],
                     [ 1.0, 14.0, 26.0, 15.5]])

더운가 = 기온 > 20
print(더운가)
print(기온[더운가])                 # 참인 칸만 골라 1차원으로
print(기온[[0, 2]])                 # 0번, 2번 도시만 (목록으로 고르기)

얼음 = 기온.clone()
얼음[얼음 < 5] = 0.0               # 5도 미만은 0으로 바꾸기
print(얼음)
