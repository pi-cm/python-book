import torch

# 3개 도시 × 4분기 평균 기온 (예제용 숫자)
기온 = torch.tensor([[ 2.0, 13.5, 25.7, 15.0],
                     [ 4.5, 15.0, 25.0, 17.5],
                     [ 1.0, 14.0, 26.0, 15.5]])

print(기온[0])          # 첫 번째 도시의 네 분기
print(기온[0, 2])       # 첫 번째 도시의 3분기
print(기온[:, 2])       # 모든 도시의 3분기 (세로 한 줄)
print(기온[1:, :2])     # 두 번째 도시부터, 1~2분기
print(기온[-1])         # 마지막 도시
