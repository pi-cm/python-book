# [2권 Chapter 5. 자동 미분과 경사하강법 · 5.1 기울기: 조금 움직였을 때 얼마나 변하나 · manuscript-vol2/chapters/05-autograd.md:152]
def 높이(x: float, y: float) -> float:
    """두 방향(동서 x, 남북 y)으로 펼쳐진 언덕의 높이."""
    return x ** 2 + 3 * y ** 2


h = 1e-5
x, y = 1.0, 2.0
동서_기울기 = (높이(x + h, y) - 높이(x - h, y)) / (2 * h)   # y는 그대로 두고 x만 움직이기
남북_기울기 = (높이(x, y + h) - 높이(x, y - h)) / (2 * h)   # x는 그대로 두고 y만 움직이기
print(f"동서 방향 기울기: {동서_기울기:.4f}  (공식 2x = {2 * x})")
print(f"남북 방향 기울기: {남북_기울기:.4f}  (공식 6y = {6 * y})")

# 기울기 반대 방향으로 아주 조금 걸어 보면 높이가 내려가는지 확인
걸음 = 0.01
print(f"지금 높이: {높이(x, y):.4f}")
print(f"기울기 반대로 한 걸음: {높이(x - 걸음 * 동서_기울기, y - 걸음 * 남북_기울기):.4f}")
print(f"기울기 방향으로 한 걸음: {높이(x + 걸음 * 동서_기울기, y + 걸음 * 남북_기울기):.4f}")
