# [2권 Chapter 5. 자동 미분과 경사하강법 · 5.10 학습률: 너무 크면 튀고, 너무 작으면 늦다 · manuscript-vol2/chapters/05-autograd.md:878]
# f(x) = x^2 (가장 낮은 곳은 x=0), 기울기는 2x, x=5에서 출발
for 학습률 in [0.01, 0.1, 0.5, 0.9, 1.1]:
    x = 5.0
    자취 = []
    for 걸음 in range(1, 21):
        x = x - 학습률 * 2 * x
        if 걸음 in (1, 2, 3, 10, 20):
            자취.append(f"{x:9.3f}")
    print(f"학습률 {학습률:<4}: 1, 2, 3, 10, 20걸음 뒤 x =", " ".join(자취))
