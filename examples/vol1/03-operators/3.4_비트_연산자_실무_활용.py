class 권한플래그:
    """비트 플래그를 사용한 권한 관리"""
    읽기 = 1      # 0001
    쓰기 = 2      # 0010
    실행 = 4      # 0100
    삭제 = 8      # 1000
    
    @staticmethod
    def 권한_추가(현재권한: int, 새권한: int) -> int:
        """권한 추가"""
        return 현재권한 | 새권한
    
    @staticmethod
    def 권한_제거(현재권한: int, 제거권한: int) -> int:
        """권한 제거"""
        return 현재권한 & ~제거권한
    
    @staticmethod
    def 권한_확인(현재권한: int, 확인권한: int) -> bool:
        """권한 확인"""
        return (현재권한 & 확인권한) == 확인권한
    
    @staticmethod
    def 권한_토글(현재권한: int, 토글권한: int) -> int:
        """권한 토글"""
        return 현재권한 ^ 토글권한
    
    @staticmethod
    def 권한_문자열(권한: int) -> str:
        """권한을 문자열로 표현"""
        권한_목록 = []
        if 권한 & 권한플래그.읽기: 권한_목록.append("읽기")
        if 권한 & 권한플래그.쓰기: 권한_목록.append("쓰기")
        if 권한 & 권한플래그.실행: 권한_목록.append("실행")
        if 권한 & 권한플래그.삭제: 권한_목록.append("삭제")
        return ", ".join(권한_목록) if 권한_목록 else "권한 없음"

# 권한 플래그 사용 예제
사용자권한 = 0  # 권한 없음

# 읽기, 쓰기 권한 추가
사용자권한 = 권한플래그.권한_추가(사용자권한, 권한플래그.읽기 | 권한플래그.쓰기)
print(f"권한 추가 후: {권한플래그.권한_문자열(사용자권한)}")

# 실행 권한 확인
if 권한플래그.권한_확인(사용자권한, 권한플래그.실행):
    print("실행 권한 있음")
else:
    print("실행 권한 없음")

# 쓰기 권한 제거
사용자권한 = 권한플래그.권한_제거(사용자권한, 권한플래그.쓰기)
print(f"쓰기 권한 제거 후: {권한플래그.권한_문자열(사용자권한)}")

# 실행 권한 토글
사용자권한 = 권한플래그.권한_토글(사용자권한, 권한플래그.실행)
print(f"실행 권한 토글 후: {권한플래그.권한_문자열(사용자권한)}")

