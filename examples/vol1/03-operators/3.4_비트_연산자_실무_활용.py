class 색상처리:
    """RGB 색상을 32비트 정수로 처리"""
    
    @staticmethod
    def rgb_to_int(r: int, g: int, b: int, a: int = 255) -> int:
        """RGBA 값을 32비트 정수로 변환"""
        return (a << 24) | (r << 16) | (g << 8) | b
    
    @staticmethod
    def int_to_rgba(색상값: int) -> tuple:
        """32비트 정수를 RGBA 값으로 변환"""
        a = (색상값 >> 24) & 0xFF
        r = (색상값 >> 16) & 0xFF
        g = (색상값 >> 8) & 0xFF
        b = 색상값 & 0xFF
        return (r, g, b, a)
    
    @staticmethod
    def 밝기_조절(색상값: int, 비율: float) -> int:
        """색상의 밝기를 조절"""
        r, g, b, a = 색상처리.int_to_rgba(색상값)
        
        # 밝기 조절 (0.0 ~ 2.0)
        r = min(255, int(r * 비율))
        g = min(255, int(g * 비율))
        b = min(255, int(b * 비율))
        
        return 색상처리.rgb_to_int(r, g, b, a)
    
    @staticmethod
    def 색상_혼합(색상1: int, 색상2: int, 비율: float = 0.5) -> int:
        """두 색상을 혼합"""
        r1, g1, b1, a1 = 색상처리.int_to_rgba(색상1)
        r2, g2, b2, a2 = 색상처리.int_to_rgba(색상2)
        
        r = int(r1 * (1 - 비율) + r2 * 비율)
        g = int(g1 * (1 - 비율) + g2 * 비율)
        b = int(b1 * (1 - 비율) + b2 * 비율)
        a = int(a1 * (1 - 비율) + a2 * 비율)
        
        return 색상처리.rgb_to_int(r, g, b, a)

# 색상 처리 예제
빨강 = 색상처리.rgb_to_int(255, 0, 0)
파랑 = 색상처리.rgb_to_int(0, 0, 255)

print(f"빨강색 값: {빨강} (0x{빨강:08X})")
print(f"파랑색 값: {파랑} (0x{파랑:08X})")

# 색상 분리
r, g, b, a = 색상처리.int_to_rgba(빨강)
print(f"빨강색 분리: R={r}, G={g}, B={b}, A={a}")

# 밝기 조절
어두운_빨강 = 색상처리.밝기_조절(빨강, 0.5)
밝은_빨강 = 색상처리.밝기_조절(빨강, 1.5)
print(f"어두운 빨강: 0x{어두운_빨강:08X}")
print(f"밝은 빨강: 0x{밝은_빨강:08X}")

# 색상 혼합
보라 = 색상처리.색상_혼합(빨강, 파랑)
print(f"보라색 (빨강+파랑): 0x{보라:08X}")

