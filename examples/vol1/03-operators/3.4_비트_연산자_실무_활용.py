def 간단한_해시(문자열: str) -> int:
    """간단한 문자열 해시 함수"""
    해시값 = 0
    for 문자 in 문자열:
        해시값 = ((해시값 << 5) - 해시값) + ord(문자)
        해시값 &= 0xFFFFFFFF  # 32비트로 제한
    return 해시값

def 체크섬_계산(데이터: bytes) -> int:
    """간단한 체크섬 계산"""
    체크섬 = 0
    for 바이트 in 데이터:
        체크섬 ^= 바이트  # XOR 체크섬
    return 체크섬

# 해시 함수 테스트
테스트_문자열들 = ["안녕하세요", "Hello", "Python", "파이썬"]
for 문자열 in 테스트_문자열들:
    해시값 = 간단한_해시(문자열)
    print(f"'{문자열}' 해시: {해시값} (0x{해시값:08X})")

# 체크섬 테스트
원본_데이터 = "파이썬 프로그래밍".encode('utf-8')
체크섬 = 체크섬_계산(원본_데이터)
print(f"\n원본 데이터 체크섬: {체크섬}")

# 데이터 손상 시뮬레이션
손상된_데이터 = bytearray(원본_데이터)
손상된_데이터[0] ^= 1  # 첫 번째 바이트의 LSB 플립
손상된_체크섬 = 체크섬_계산(bytes(손상된_데이터))
print(f"손상된 데이터 체크섬: {손상된_체크섬}")
print(f"데이터 무결성: {'OK' if 체크섬 == 손상된_체크섬 else 'FAIL'}")
