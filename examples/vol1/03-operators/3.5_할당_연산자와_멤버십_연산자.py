# 기본 멤버십 연산
과일들 = ["사과", "바나나", "오렌지", "포도"]
print(f"'사과' in 과일들: {'사과' in 과일들}")
print(f"'수박' not in 과일들: {'수박' not in 과일들}")

# 문자열에서의 멤버십
문장 = "파이썬은 훌륭한 프로그래밍 언어입니다"
print(f"'파이썬' in 문장: {'파이썬' in 문장}")
print(f"'자바' not in 문장: {'자바' not in 문장}")

# 딕셔너리에서의 멤버십 (키만 확인)
학생_성적 = {"김철수": 90, "이영희": 85, "박민수": 92}
print(f"'김철수' in 학생_성적: {'김철수' in 학생_성적}")
print(f"90 in 학생_성적.values(): {90 in 학생_성적.values()}")

# range 객체에서의 멤버십
숫자범위 = range(1, 101)  # 1부터 100까지
print(f"50 in range(1, 101): {50 in 숫자범위}")
print(f"150 in range(1, 101): {150 in 숫자범위}")

# 집합에서의 멤버십 (매우 빠름)
큰_집합 = set(range(1000000))
print(f"999999 in 큰_집합: {999999 in 큰_집합}")  # O(1) 시간 복잡도

# 사용자 정의 클래스에서의 멤버십
class 한국어_리스트:
    def __init__(self, 항목들):
        self.항목들 = 항목들
    
    def __contains__(self, 항목):
        """in 연산자 구현"""
        return 항목 in self.항목들

한국_도시들 = 한국어_리스트(["서울", "부산", "대구", "인천"])
print(f"'서울' in 한국_도시들: {'서울' in 한국_도시들}")
