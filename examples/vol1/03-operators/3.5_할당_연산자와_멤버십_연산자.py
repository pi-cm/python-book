# ---- 원고 739줄 ----
# 기본 할당
x = 10
print(f"x = {x}")

# 복합 할당 연산자
x += 5   # x = x + 5
print(f"x += 5: {x}")

x -= 3   # x = x - 3  
print(f"x -= 3: {x}")

x *= 2   # x = x * 2
print(f"x *= 2: {x}")

x /= 4   # x = x / 4
print(f"x /= 4: {x}")

x //= 2  # x = x // 2
print(f"x //= 2: {x}")

x %= 3   # x = x % 3
print(f"x %= 3: {x}")

x **= 3  # x = x ** 3
print(f"x **= 3: {x}")

# 비트 할당 연산자
y = 60  # 0011 1100
print(f"y = {y} ({y:08b})")

y &= 13  # y = y & 13
print(f"y &= 13: {y} ({y:08b})")

y = 60
y |= 13  # y = y | 13
print(f"y |= 13: {y} ({y:08b})")

y = 60
y ^= 13  # y = y ^ 13
print(f"y ^= 13: {y} ({y:08b})")

y = 60
y <<= 2  # y = y << 2
print(f"y <<= 2: {y} ({y:08b})")

y >>= 3  # y = y >> 3
print(f"y >>= 3: {y} ({y:08b})")

