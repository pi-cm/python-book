# 포매팅된 출력
def 포매팅_예제():
    # 테이블 형태 출력
    학생들 = [
        {"이름": "김철수", "국어": 90, "영어": 85, "수학": 92},
        {"이름": "이영희", "국어": 88, "영어": 92, "수학": 90},
        {"이름": "박민수", "국어": 85, "영어": 88, "수학": 95},
    ]
    
    print("=" * 50)
    print(f"{'이름':^10} {'국어':^8} {'영어':^8} {'수학':^8} {'평균':^8}")
    print("=" * 50)
    
    for 학생 in 학생들:
        평균 = (학생['국어'] + 학생['영어'] + 학생['수학']) / 3
        print(f"{학생['이름']:^10} {학생['국어']:^8} {학생['영어']:^8} {학생['수학']:^8} {평균:^8.1f}")
    
    print("=" * 50)

# 진행률 표시
def 진행률_표시(현재: int, 전체: int, 길이: int = 30):
    비율 = 현재 / 전체
    완료_길이 = int(길이 * 비율)
    바 = "█" * 완료_길이 + "░" * (길이 - 완료_길이)
    퍼센트 = 비율 * 100
    print(f"\r진행률: [{바}] {퍼센트:5.1f}% ({현재}/{전체})", end="", flush=True)

# 컬러 출력 (ANSI 코드)
class 색상:
    빨강 = '\033[91m'
    녹색 = '\033[92m'
    노랑 = '\033[93m'
    파랑 = '\033[94m'
    보라 = '\033[95m'
    청록 = '\033[96m'
    끝 = '\033[0m'

def 컬러_출력_예제():
    print(f"{색상.빨강}빨간 텍스트{색상.끝}")
    print(f"{색상.녹색}초록 텍스트{색상.끝}")
    print(f"{색상.파랑}파란 텍스트{색상.끝}")
    
    # 배경색도 가능
    print(f"\033[41m빨간 배경\033[0m")
    print(f"\033[42m초록 배경\033[0m")

# 실행
