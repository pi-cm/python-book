from typing import Generator, Dict, Any
import json
from datetime import datetime, timedelta

def 주식_데이터_생성기(
    종목코드: str, 
    시작일: str, 
    일수: int = 30
) -> Generator[Dict[str, Any], None, None]:
    """한국 주식 데이터 시뮬레이션 제너레이터"""
    
    import random
    
    # 한국 주요 종목 정보
    종목_정보 = {
        '005930': {'회사명': '삼성전자', '기준가': 75000},
        '000660': {'회사명': 'SK하이닉스', '기준가': 130000},
        '035420': {'회사명': 'NAVER', '기준가': 350000},
        '051910': {'회사명': 'LG화학', '기준가': 800000},
        '006400': {'회사명': '삼성SDI', '기준가': 650000}
    }
    
    if 종목코드 not in 종목_정보:
        raise ValueError(f"지원하지 않는 종목코드: {종목코드}")
    
    회사_정보 = 종목_정보[종목코드]
    현재가 = 회사_정보['기준가']
    
    # 시작일 파싱
    시작_날짜 = datetime.strptime(시작일, '%Y-%m-%d')
    
    for i in range(일수):
        현재_날짜 = 시작_날짜 + timedelta(days=i)
        
        # 주말 건너뛰기
        if 현재_날짜.weekday() >= 5:  # 토요일(5), 일요일(6)
            continue
        
        # 가격 변동 시뮬레이션 (-5% ~ +5%)
        변동율 = random.uniform(-0.05, 0.05)
        현재가 = int(현재가 * (1 + 변동율))
        
        # 거래량 시뮬레이션
        거래량 = random.randint(100000, 2000000)
        
        yield {
            '날짜': 현재_날짜.strftime('%Y-%m-%d'),
            '종목코드': 종목코드,
            '회사명': 회사_정보['회사명'],
            '종가': 현재가,
            '거래량': 거래량,
            '변동율': round(변동율 * 100, 2)
        }

# 사용 예제
print("삼성전자 주식 데이터 (첫 10일):")
삼성전자_데이터 = 주식_데이터_생성기('005930', '2024-01-01', 20)

for i, 일일_데이터 in enumerate(삼성전자_데이터):
    if i >= 10:
        break
    print(f"  {일일_데이터['날짜']}: {일일_데이터['종가']:,}원 "
          f"({일일_데이터['변동율']:+.1f}%) "
          f"거래량: {일일_데이터['거래량']:,}")

