def 지역별_관광지():
    """지역별 주요 관광지 제너레이터"""
    
    def 서울_관광지():
        서울_명소 = ['경복궁', '남산타워', '명동', '인사동', '강남']
        for 명소 in 서울_명소:
            yield f"서울 - {명소}"
    
    def 부산_관광지():
        부산_명소 = ['해운대', '광안리', '태종대', '감천문화마을', '자갈치시장']
        for 명소 in 부산_명소:
            yield f"부산 - {명소}"
    
    def 제주_관광지():
        제주_명소 = ['한라산', '성산일출봉', '우도', '천지연폭포', '협재해수욕장']
        for 명소 in 제주_명소:
            yield f"제주 - {명소}"
    
    # yield from을 사용하여 여러 제너레이터 연결
    print("서울 관광지:")
    yield from 서울_관광지()
    
    print("\n부산 관광지:")
    yield from 부산_관광지()
    
    print("\n제주 관광지:")
    yield from 제주_관광지()

# 사용 예제
print("전국 주요 관광지:")
for 관광지 in 지역별_관광지():
    print(f"  {관광지}")

