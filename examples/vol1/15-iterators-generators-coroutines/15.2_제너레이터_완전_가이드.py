from typing import Generator, List, Iterator, TypeVar

T = TypeVar('T')

def 배치_처리기(
    데이터: Iterator[T], 
    배치_크기: int = 100
) -> Generator[List[T], None, None]:
    """데이터를 지정된 크기의 배치로 나누는 제너레이터"""
    
    배치 = []
    
    for 항목 in 데이터:
        배치.append(항목)
        
        if len(배치) == 배치_크기:
            yield 배치
            배치 = []
    
    # 남은 데이터가 있으면 마지막 배치로 반환
    if 배치:
        yield 배치

