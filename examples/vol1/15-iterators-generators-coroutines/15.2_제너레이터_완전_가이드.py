def 한국_뉴스_처리기():
    """한국 뉴스를 처리하는 제너레이터"""
    뉴스_카테고리 = '정치'  # 기본 카테고리
    뉴스_번호 = 1
    
    while True:
        try:
            # 외부에서 새로운 카테고리를 받을 수 있음
            새_카테고리 = yield f"[{뉴스_카테고리}] 뉴스 #{뉴스_번호}"
            
            if 새_카테고리:
                print(f"  카테고리를 '{뉴스_카테고리}'에서 '{새_카테고리}'로 변경")
                뉴스_카테고리 = 새_카테고리
            
            뉴스_번호 += 1
            
        except GeneratorExit:
            print("  뉴스 처리기 종료됨")
            break
        except Exception as e:
            print(f"  에러 발생: {e}")
            뉴스_번호 += 1  # 에러가 나도 계속 처리

# 제너레이터 메서드 사용 예제
print("제너레이터 메서드 활용:")
뉴스_처리기 = 한국_뉴스_처리기()

# 첫 번째 뉴스
print(f"1. {next(뉴스_처리기)}")

# send()로 카테고리 변경
print(f"2. {뉴스_처리기.send('경제')}")
print(f"3. {뉴스_처리기.send('스포츠')}")

# throw()로 예외 던지기 (제너레이터가 예외를 처리한 뒤 다음 뉴스를 돌려줌)
print(f"4. {뉴스_처리기.throw(RuntimeError('네트워크 연결 오류'))}")

print(f"5. {next(뉴스_처리기)}")

# close()로 제너레이터 종료
뉴스_처리기.close()

