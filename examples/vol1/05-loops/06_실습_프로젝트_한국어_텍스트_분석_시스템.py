import re
from collections import Counter, defaultdict
from typing import Dict, List, Tuple
import time

class 한국어텍스트분석기:
    """한국어 텍스트를 종합적으로 분석하는 시스템"""
    
    def __init__(self):
        self.조사_목록 = {'이', '가', '을', '를', '에', '의', '로', '으로', '에서', '와', '과', '도', '만', '까지', '부터'}
        self.어미_패턴 = re.compile(r'(다|요|니다|습니다|세요|ㅂ니다)$')
        self.한글_패턴 = re.compile(r'[가-힣]+')
        
    def 텍스트_전처리(self, 텍스트: str) -> str:
        """텍스트 전처리 및 정규화"""
        # 불필요한 공백 제거
        텍스트 = re.sub(r'\s+', ' ', 텍스트.strip())
        
        # 특수문자 정리 (한글, 영어, 숫자, 기본 문장부호만 유지)
        텍스트 = re.sub(r'[^\w\s가-힣.,!?]', '', 텍스트)
        
        return 텍스트
    
    def 문장_분리(self, 텍스트: str) -> List[str]:
        """문장 단위로 분리"""
        # 한국어 문장 끝 패턴
        문장_패턴 = re.compile(r'[.!?]+\s*')
        문장들 = 문장_패턴.split(텍스트)
        
        # 빈 문장 제거 및 정리
        return [문장.strip() for 문장 in 문장들 if 문장.strip()]
    
    def 단어_추출(self, 텍스트: str) -> List[str]:
        """한글 단어만 추출 (간단한 공백 기반 분리)"""
        단어들 = []
        
        # 공백으로 분리 후 한글만 필터링
        for 토큰 in 텍스트.split():
            한글_매치 = self.한글_패턴.findall(토큰)
            단어들.extend(한글_매치)
        
        # 조사 제거 (간단한 방식)
        정제된_단어들 = []
        for 단어 in 단어들:
            if len(단어) > 1 and 단어 not in self.조사_목록:
                정제된_단어들.append(단어)
        
        return 정제된_단어들
    
    def 빈도_분석(self, 단어들: List[str], 상위_N: int = 10) -> List[Tuple[str, int]]:
        """단어 빈도 분석"""
        빈도_카운터 = Counter(단어들)
        return 빈도_카운터.most_common(상위_N)
    
    def 문장_길이_분석(self, 문장들: List[str]) -> Dict[str, float]:
        """문장 길이 통계"""
        if not 문장들:
            return {"평균": 0, "최대": 0, "최소": 0}
        
        길이들 = [len(문장) for 문장 in 문장들]
        
        return {
            "평균": sum(길이들) / len(길이들),
            "최대": max(길이들),
            "최소": min(길이들),
            "총_문장수": len(문장들)
        }
    
    def 특성_분석(self, 텍스트: str) -> Dict[str, int]:
        """텍스트 특성 분석"""
        특성들 = defaultdict(int)
        
        for 문자 in 텍스트:
            if '\uac00' <= 문자 <= '\ud7a3':  # 한글
                특성들['한글'] += 1
            elif 문자.isalpha():  # 영어
                특성들['영어'] += 1
            elif 문자.isdigit():  # 숫자
                특성들['숫자'] += 1
            elif 문자 in '.,!?':  # 문장부호
                특성들['문장부호'] += 1
            elif 문자.isspace():  # 공백
                특성들['공백'] += 1
            else:  # 기타
                특성들['기타'] += 1
        
        return dict(특성들)
    
    def 종성_분석(self, 단어들: List[str]) -> Dict[str, int]:
        """단어 끝 글자(종성) 분석"""
        종성_카운터 = Counter()
        
        for 단어 in 단어들:
            if 단어 and '\uac00' <= 단어[-1] <= '\ud7a3':
                종성_카운터[단어[-1]] += 1
        
        return dict(종성_카운터.most_common(10))
    
    def 문체_분석(self, 문장들: List[str]) -> Dict[str, int]:
        """문체 패턴 분석"""
        문체_패턴 = defaultdict(int)
        
        for 문장 in 문장들:
            if re.search(r'습니다|ㅂ니다', 문장):
                문체_패턴['격식체'] += 1
            elif re.search(r'해요|세요|어요|아요', 문장):
                문체_패턴['해요체'] += 1
            elif re.search(r'한다|된다|이다', 문장):
                문체_패턴['해라체'] += 1
            elif '?' in 문장:
                문체_패턴['의문문'] += 1
            elif '!' in 문장:
                문체_패턴['감탄문'] += 1
            else:
                문체_패턴['평서문'] += 1
        
        return dict(문체_패턴)
    
    def 종합_분석(self, 텍스트: str) -> Dict:
        """텍스트 종합 분석"""
        시작_시간 = time.time()
        
        # 전처리
        정제된_텍스트 = self.텍스트_전처리(텍스트)
        
        # 문장 분리
        문장들 = self.문장_분리(정제된_텍스트)
        
        # 단어 추출
        단어들 = self.단어_추출(정제된_텍스트)
        
        # 각종 분석 수행
        분석_결과 = {
            "기본_정보": {
                "원본_길이": len(텍스트),
                "정제_후_길이": len(정제된_텍스트),
                "총_문장_수": len(문장들),
                "총_단어_수": len(단어들),
                "유니크_단어_수": len(set(단어들))
            },
            "빈도_분석": self.빈도_분석(단어들, 10),
            "문장_길이": self.문장_길이_분석(문장들),
            "문자_특성": self.특성_분석(정제된_텍스트),
            "종성_분석": self.종성_분석(단어들),
            "문체_분석": self.문체_분석(문장들),
            "처리_시간": time.time() - 시작_시간
        }
        
        return 분석_결과
    
    def 결과_출력(self, 분석_결과: Dict):
        """분석 결과를 보기 좋게 출력"""
        print("=" * 60)
        print("한국어 텍스트 분석 결과")
        print("=" * 60)
        
        # 기본 정보
        기본_정보 = 분석_결과["기본_정보"]
        print(f"\n기본 정보:")
        print(f"  • 원본 길이: {기본_정보['원본_길이']:,}자")
        print(f"  • 정제 후 길이: {기본_정보['정제_후_길이']:,}자")
        print(f"  • 총 문장 수: {기본_정보['총_문장_수']:,}개")
        print(f"  • 총 단어 수: {기본_정보['총_단어_수']:,}개")
        print(f"  • 유니크 단어 수: {기본_정보['유니크_단어_수']:,}개")
        
        # 빈도 분석
        print(f"\n단어 빈도 TOP 10:")
        for 순위, (단어, 빈도) in enumerate(분석_결과["빈도_분석"], 1):
            print(f"  {순위:2d}. {단어} ({빈도}회)")
        
        # 문장 길이 통계
        문장_통계 = 분석_결과["문장_길이"]
        print(f"\n문장 길이 통계:")
        print(f"  • 평균 길이: {문장_통계['평균']:.1f}자")
        print(f"  • 최대 길이: {문장_통계['최대']}자")
        print(f"  • 최소 길이: {문장_통계['최소']}자")
        
        # 문자 특성
        문자_특성 = 분석_결과["문자_특성"]
        전체_문자수 = sum(문자_특성.values())
        print(f"\n문자 구성 (총 {전체_문자수:,}자):")
        for 문자_타입, 개수 in 문자_특성.items():
            비율 = (개수 / 전체_문자수) * 100
            print(f"  • {문자_타입}: {개수:,}자 ({비율:.1f}%)")
        
        # 종성 분석
        print(f"\n단어 끝 글자 TOP 10:")
        for 순위, (글자, 빈도) in enumerate(분석_결과["종성_분석"].items(), 1):
            print(f"  {순위:2d}. '{글자}' ({빈도}회)")
        
        # 문체 분석
        문체_분석 = 분석_결과["문체_분석"]
        전체_문장수 = sum(문체_분석.values())
        print(f"\n문체 분석 (총 {전체_문장수}문장):")
        for 문체, 개수 in 문체_분석.items():
            비율 = (개수 / 전체_문장수) * 100
            print(f"  • {문체}: {개수}문장 ({비율:.1f}%)")
        
        # 처리 시간
        print(f"\n처리 시간: {분석_결과['처리_시간']:.3f}초")
        print("=" * 60)

