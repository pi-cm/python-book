# 1. 안전한 카운터 기반 while
def 안전한_카운터_루프(최대_반복=1000):
    """안전장치가 있는 카운터 루프"""
    카운터 = 0
    처리_건수 = 0
    
    while 카운터 < 최대_반복:
        카운터 += 1
        
        # 특정 조건에서만 처리
        if 카운터 % 17 == 0:  # 17의 배수만 처리
            처리_건수 += 1
            print(f"처리: {카운터} (총 {처리_건수}건 처리)")
            
            # 목표 달성 시 조기 종료
            if 처리_건수 >= 5:
                print("목표 달성으로 조기 종료")
                break
    else:
        # while 루프가 break 없이 끝난 경우
        print("최대 반복 횟수에 도달했습니다.")
    
    return 처리_건수

결과 = 안전한_카운터_루프()
print(f"총 {결과}건 처리됨\n")

# 2. 상태 기반 while 루프 (유한 상태 기계)
class 간단한_상태기계:
    def __init__(self):
        self.상태 = "대기"
        self.카운터 = 0
    
    def 상태_전환(self):
        """상태 전환 로직"""
        self.카운터 += 1
        
        if self.상태 == "대기":
            if self.카운터 >= 3:
                self.상태 = "작업중"
                self.카운터 = 0
        elif self.상태 == "작업중":
            if self.카운터 >= 5:
                self.상태 = "완료"
        
        return self.상태 != "완료"

상태기계 = 간단한_상태기계()
총_스텝 = 0

print("=== 상태 기계 시뮬레이션 ===")
while 상태기계.상태_전환() and 총_스텝 < 20:  # 안전장치
    총_스텝 += 1
    print(f"스텝 {총_스텝}: 상태='{상태기계.상태}', 카운터={상태기계.카운터}")

print(f"최종 상태: {상태기계.상태}")

# 3. 리소스 모니터링 while 루프
import time
from datetime import datetime, timedelta

def 시스템_모니터링_시뮬레이션(모니터링_시간_초=5):
    """시스템 모니터링 시뮬레이션"""
    시작시간 = datetime.now()
    종료시간 = 시작시간 + timedelta(seconds=모니터링_시간_초)
    
    메모리_사용률들 = [45, 52, 48, 65, 73, 68, 59, 44, 38, 42]
    인덱스 = 0
    
    print("=== 시스템 모니터링 시뮬레이션 ===")
    
    while datetime.now() < 종료시간:
        현재_메모리 = 메모리_사용률들[인덱스 % len(메모리_사용률들)]
        인덱스 += 1
        
        print(f"{datetime.now().strftime('%H:%M:%S')} - 메모리 사용률: {현재_메모리}%")
        
        # 임계치 확인
        if 현재_메모리 > 70:
            print(f"[!] 경고: 메모리 사용률이 {현재_메모리}%로 높습니다!")
        
        # 시뮬레이션 딜레이
        time.sleep(0.5)
    
    print("모니터링 완료")

