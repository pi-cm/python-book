# 2. 대용량 데이터 처리에서 제너레이터 활용
def 큰_수_제너레이터(최대값):
    """메모리 효율적인 큰 수 처리"""
    for i in range(최대값):
        if i % 1000 == 0:  # 1000의 배수만
            yield i * i

print(f"\n\n=== 대용량 데이터 처리 ===")
큰_제곱들 = 큰_수_제너레이터(10000)
print(f"생성된 제너레이터: {큰_제곱들}")

# 처음 5개만 출력
처음_5개 = []
for i, 값 in enumerate(큰_제곱들):
    if i >= 5:
        break
    처음_5개.append(값)

print(f"처음 5개 값: {처음_5개}")

# 3. 파일 처리에서 제너레이터 활용
def 가짜_파일_라인_제너레이터():
    """파일 라인을 시뮬레이션하는 제너레이터"""
    가짜_라인들 = [
        "첫 번째 라인입니다",
        "두 번째 라인입니다", 
        "세 번째 라인입니다",
        "네 번째 라인입니다",
        "다섯 번째 라인입니다"
    ]
    for 라인 in 가짜_라인들:
        yield 라인

# 조건에 맞는 라인만 필터링 (메모리 효율적)
필터링된_라인들 = (라인.upper() for 라인 in 가짜_파일_라인_제너레이터() 
                if "번째" in 라인)

print(f"\n=== 파일 라인 필터링 ===")
for 라인 in 필터링된_라인들:
    print(라인)

