# [X] 나쁜 예: 깊은 중첩
def 나쁜_주문_처리(주문):
    if 주문:
        if 주문.get("사용자"):
            if 주문["사용자"].get("인증됨"):
                if 주문.get("상품들"):
                    if len(주문["상품들"]) > 0:
                        if 주문.get("결제정보"):
                            if 주문["결제정보"].get("유효함"):
                                return "주문 처리 완료"
                            else:
                                return "결제정보가 유효하지 않음"
                        else:
                            return "결제정보가 없음"
                    else:
                        return "상품이 없음"
                else:
                    return "상품 목록이 없음"
            else:
                return "사용자 인증 실패"
        else:
            return "사용자 정보가 없음"
    else:
        return "주문 정보가 없음"

# [O] 좋은 예: 조기 반환 (Early Return) 패턴
def 좋은_주문_처리(주문):
    # 조기 반환으로 중첩 제거
    if not 주문:
        return "주문 정보가 없음"
    
    if not 주문.get("사용자"):
        return "사용자 정보가 없음"
    
    if not 주문["사용자"].get("인증됨"):
        return "사용자 인증 실패"
    
    if not 주문.get("상품들"):
        return "상품 목록이 없음"
    
    if len(주문["상품들"]) == 0:
        return "상품이 없음"
    
    if not 주문.get("결제정보"):
        return "결제정보가 없음"
    
    if not 주문["결제정보"].get("유효함"):
        return "결제정보가 유효하지 않음"
    
    return "주문 처리 완료"

# [O] 더 좋은 예: 검증 함수 분리
def 주문_검증(주문):
    """주문 유효성 검증"""
    # 주문이 None이면 아래 .get()이 오류를 내므로 먼저 걸러 낸다
    if not 주문:
        return False, "주문 정보가 없음"
    
    검증_규칙들 = [
        (주문, "주문 정보가 없음"),
        (주문.get("사용자"), "사용자 정보가 없음"),
        (주문["사용자"].get("인증됨") if 주문.get("사용자") else False, "사용자 인증 실패"),
        (주문.get("상품들"), "상품 목록이 없음"),
        (len(주문.get("상품들", [])) > 0, "상품이 없음"),
        (주문.get("결제정보"), "결제정보가 없음"),
        (주문.get("결제정보", {}).get("유효함"), "결제정보가 유효하지 않음")
    ]
    
    for 조건, 오류메시지 in 검증_규칙들:
        if not 조건:
            return False, 오류메시지
    
    return True, "검증 성공"

def 최고의_주문_처리(주문):
    유효함, 메시지 = 주문_검증(주문)
    return "주문 처리 완료" if 유효함 else 메시지

