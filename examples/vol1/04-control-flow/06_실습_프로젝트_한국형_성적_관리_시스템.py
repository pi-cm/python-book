class 성적관리시스템:
    def __init__(self):
        self.학생들: Dict[str, 학생] = {}
        self.성적_기준 = {
            95: "A+", 90: "A", 85: "B+", 80: "B",
            75: "C+", 70: "C", 65: "D+", 60: "D"
        }
    
    def 학생_등록(self, 학번: str, 이름: str, 학과: str, 학년: int):
        """새 학생 등록"""
        if 학번 in self.학생들:
            return False, "이미 등록된 학번입니다"
        
        # 학번 형식 검증 (예: 2024001)
        if not (len(학번) == 7 and 학번.isdigit()):
            return False, "학번은 7자리 숫자여야 합니다"
        
        # 학년 검증
        if not (1 <= 학년 <= 4):
            return False, "학년은 1-4 사이여야 합니다"
        
        self.학생들[학번] = 학생(학번, 이름, 학과, 학년, [])
        return True, f"{이름} 학생이 등록되었습니다"
    
    def 과목_등록(self, 학번: str, 과목명: str, 학점: int):
        """학생에게 과목 등록"""
        if 학번 not in self.학생들:
            return False, "등록되지 않은 학번입니다"
        
        if not (1 <= 학점 <= 4):
            return False, "학점은 1-4 사이여야 합니다"
        
        학생_정보 = self.학생들[학번]
        
        # 중복 과목 검사
        for 기존_과목 in 학생_정보.과목들:
            if 기존_과목.과목명 == 과목명:
                return False, f"이미 등록된 과목입니다: {과목명}"
        
        새_과목 = 과목(과목명, 학점)
        학생_정보.과목들.append(새_과목)
        return True, f"{과목명} 과목이 등록되었습니다"
    
    def 성적_입력(self, 학번: str, 과목명: str, 점수: int):
        """성적 입력 및 등급 자동 계산"""
        if 학번 not in self.학생들:
            return False, "등록되지 않은 학번입니다"
        
        if not (0 <= 점수 <= 100):
            return False, "점수는 0-100 사이여야 합니다"
        
        학생_정보 = self.학생들[학번]
        
        # 과목 찾기
        대상_과목 = None
        for 과목_정보 in 학생_정보.과목들:
            if 과목_정보.과목명 == 과목명:
                대상_과목 = 과목_정보
                break
        
        if not 대상_과목:
            return False, f"등록되지 않은 과목입니다: {과목명}"
        
        # 등급 계산
        등급 = self._점수_to_등급(점수)
        
        대상_과목.점수 = 점수
        대상_과목.등급 = 등급
        
        return True, f"{과목명}: {점수}점 ({등급})"
    
    def _점수_to_등급(self, 점수: int) -> str:
        """점수를 등급으로 변환"""
        for 기준점수, 등급 in sorted(self.성적_기준.items(), reverse=True):
            if 점수 >= 기준점수:
                return 등급
        return "F"
    
    def 성적표_출력(self, 학번: str):
        """개별 학생 성적표 출력"""
        if 학번 not in self.학생들:
            return "등록되지 않은 학번입니다"
        
        학생_정보 = self.학생들[학번]
        
        print(f"\n{'='*60}")
        print(f"성적표")
        print(f"{'='*60}")
        print(f"학번: {학생_정보.학번}")
        print(f"이름: {학생_정보.이름}")
        print(f"학과: {학생_정보.학과}")
        print(f"학년: {학생_정보.학년}학년")
        print(f"{'='*60}")
        print(f"{'과목명':^15} {'학점':^5} {'점수':^5} {'등급':^5}")
        print(f"{'-'*60}")
        
        총_학점 = 0
        이수_학점 = 0
        
        for 과목_정보 in 학생_정보.과목들:
            점수_표시 = str(과목_정보.점수) if 과목_정보.점수 is not None else "-"
            등급_표시 = 과목_정보.등급 if 과목_정보.등급 else "-"
            
            print(f"{과목_정보.과목명:^15} {과목_정보.학점:^5} {점수_표시:^5} {등급_표시:^5}")
            
            총_학점 += 과목_정보.학점
            if 과목_정보.등급 and 과목_정보.등급 != "F":
                이수_학점 += 과목_정보.학점
        
        print(f"{'-'*60}")
        print(f"총 등록 학점: {총_학점}")
        print(f"이수 학점: {이수_학점}")
        print(f"평점평균: {학생_정보.평점_계산():.2f}/4.5")
        print(f"학사등급: {학생_정보.학점_등급()}")
        print(f"{'='*60}")
    
    def 학과별_통계(self, 학과명: str):
        """학과별 성적 통계"""
        해당_학생들 = [
            학생 for 학생 in self.학생들.values() 
            if 학생.학과 == 학과명
        ]
        
        if not 해당_학생들:
            return f"{학과명} 학과에 등록된 학생이 없습니다"
        
        print(f"\n{학과명} 학과 성적 통계")
        print(f"{'='*50}")
        
        # 학년별 분포
        학년별_분포 = {}
        평점_합계 = 0
        유효_학생수 = 0
        
        for 학생 in 해당_학생들:
            학년별_분포[학생.학년] = 학년별_분포.get(학생.학년, 0) + 1
            
            평점 = 학생.평점_계산()
            if 평점 > 0:
                평점_합계 += 평점
                유효_학생수 += 1
        
        print(f"총 학생 수: {len(해당_학생들)}명")
        print(f"학년별 분포:")
        for 학년 in sorted(학년별_분포.keys()):
            print(f"  {학년}학년: {학년별_분포[학년]}명")
        
        if 유효_학생수 > 0:
            평균_평점 = 평점_합계 / 유효_학생수
            print(f"학과 평균 평점: {평균_평점:.2f}/4.5")
            
            # 우수학생 (평점 4.0 이상)
            우수학생들 = [
                학생 for 학생 in 해당_학생들 
                if 학생.평점_계산() >= 4.0
            ]
            print(f"우수학생 ({len(우수학생들)}명):")
            for 학생 in 우수학생들:
                print(f"  {학생.이름} ({학생.학번}) - {학생.평점_계산():.2f}")
    
    def 데이터_저장(self, 파일명: str):
        """성적 데이터를 JSON으로 저장"""
        데이터 = {}
        for 학번, 학생_정보 in self.학생들.items():
            데이터[학번] = {
                "이름": 학생_정보.이름,
                "학과": 학생_정보.학과,
                "학년": 학생_정보.학년,
                "과목들": [
                    {
                        "과목명": 과목.과목명,
                        "학점": 과목.학점,
                        "점수": 과목.점수,
                        "등급": 과목.등급
                    }
                    for 과목 in 학생_정보.과목들
                ]
            }
        
        try:
            with open(파일명, 'w', encoding='utf-8') as f:
                json.dump(데이터, f, ensure_ascii=False, indent=2)
            return f"데이터가 {파일명}에 저장되었습니다"
        except Exception as e:
            return f"저장 실패: {e}"

