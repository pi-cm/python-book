# API 응답 처리
def API_응답_처리(상태코드, 데이터):
    return {
        "성공": 상태코드 == 200,
        "메시지": "요청 성공" if 상태코드 == 200 else f"오류 발생 (코드: {상태코드})",
        "데이터": 데이터 if 상태코드 == 200 else None
    }

# 설정값 처리
def 설정_가져오기(설정값, 기본값):
    return 설정값 if 설정값 is not None else 기본값

# 문자열 처리
def 안전한_문자열_처리(텍스트):
    return 텍스트.strip() if isinstance(텍스트, str) and 텍스트 else ""

# 날짜 포맷팅
from datetime import datetime

def 날짜_표시(날짜):
    return 날짜.strftime("%Y년 %m월 %d일") if 날짜 else "날짜 없음"

오늘 = datetime.now()
print(날짜_표시(오늘))  # 실행한 날짜 (예: 2024년 09월 05일)
print(날짜_표시(None))  # 날짜 없음
