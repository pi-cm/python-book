# 중첩된 삼항 연산자
점수 = 85
등급 = "A" if 점수 >= 90 else "B" if 점수 >= 80 else "C" if 점수 >= 70 else "F"
print(등급)  # B

# 하지만 가독성을 위해 일반 if-elif 사용 권장
def 등급_계산(점수):
    if 점수 >= 90:
        return "A"
    elif 점수 >= 80:
        return "B"
    elif 점수 >= 70:
        return "C"
    else:
        return "F"

# 리스트 컴프리헨션에서 활용
숫자들 = [-3, -1, 0, 2, 5, -2]
절댓값들 = [x if x >= 0 else -x for x in 숫자들]
print(절댓값들)  # [3, 1, 0, 2, 5, 2]

# 짝수/홀수 분류
분류된_숫자들 = [f"{x}(짝수)" if x % 2 == 0 else f"{x}(홀수)" for x in range(1, 6)]
print(분류된_숫자들)  # ['1(홀수)', '2(짝수)', '3(홀수)', '4(짝수)', '5(홀수)']

# 딕셔너리에서 활용
학생들 = [
    {"이름": "김철수", "점수": 95},
    {"이름": "이영희", "점수": 78},
    {"이름": "박민수", "점수": 82}
]

결과 = {
    학생["이름"]: "합격" if 학생["점수"] >= 80 else "불합격" 
    for 학생 in 학생들
}
print(결과)  # {'김철수': '합격', '이영희': '불합격', '박민수': '합격'}

