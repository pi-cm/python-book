import numpy as np
import torch

from 맛집데이터 import 데이터_만들기, 시간으로_나누기
from 추천학습 import 행렬분해, 학습설정, 학습하기, 좋았던_쌍

데이터 = 데이터_만들기(씨앗=0)
학습, _, _ = 시간으로_나누기(데이터.방문)
식당 = 데이터.식당
torch.manual_seed(0)
모델 = 행렬분해(len(데이터.사용자), len(식당), 차원=32)
학습하기(모델, 좋았던_쌍(학습), torch.tensor(np.flatnonzero(식당["개업일"] < 300)),
        학습설정(손실="bpr"))

벡터 = 모델.식당.weight.detach()                         # (식당 수, 32)
단위 = 벡터 / 벡터.norm(dim=1, keepdim=True)              # 4장 4.11절, 13장 13.7절처럼
아는_식당 = torch.tensor((식당["개업일"] < 300).to_numpy())  # 학습 기간에 연 식당만


def 보여_주기(번호들: list[int], 유사도: torch.Tensor) -> None:
    for i in 번호들:
        줄 = 식당.loc[i]
        print(f"  유사도 {유사도[i]:.2f} | 가격대 {줄['가격대']} | 매운맛 {줄['숨은_매운맛']:.2f} | "
              f"분위기 {줄['숨은_분위기']:+.2f} | {줄['이름']}")


for 기준 in [17, 5]:
    줄 = 식당.loc[기준]
    print(f"[기준] 가격대 {줄['가격대']} | 매운맛 {줄['숨은_매운맛']:.2f} | "
          f"분위기 {줄['숨은_분위기']:+.2f} | {줄['이름']}")
    유사도 = 단위 @ 단위[기준]
    유사도[기준] = -1                                      # 자기 자신은 빼고
    유사도[~아는_식당] = -1                                # 학습 기간에 없던 식당도 빼고
    print(" 가장 비슷한 곳")
    보여_주기(유사도.topk(3).indices.tolist(), 유사도)
    다른_동네 = 유사도.clone()
    다른_동네[torch.tensor((식당["지역"] == 줄["지역"]).to_numpy())] = -1
    print(" 다른 동네에서 가장 비슷한 곳")
    보여_주기(다른_동네.topk(3).indices.tolist(), 유사도)
